// Rendered Claude Code subagent definitions for the four pipeline roles
// (ADR 2026-034): the tool strip and the role binding on the second host.
//
// pi binds a role with two frontmatter fields: `tools:` (the allowlist — the
// only layer that PREVENTS rather than detects) and `subagentOnlyExtensions`
// (the per-role gate loader, so the role is decided by which definition
// loads). Claude Code's `.claude/agents/<name>.md` has the exact counterparts:
// `tools:` is a comma-separated allowlist, and `hooks:` in the frontmatter
// fire only inside that subagent. So a role's definition here is DERIVED from
// its pi definition, never written by hand:
//
//   · `tools:`   = ROLE_TOOLS[role] mapped through PI_TO_CLAUDE_TOOLS, deduped.
//     Every gate, git, sleep and rm collapse to Bash, which the hook then
//     narrows back to exactly those (bash-policy.ts).
//   · `hooks:`   = this host's PreToolUse hook with `--role <role>` bound.
//   · body       = a generated preamble that says how THIS host reaches each
//     pi tool, then the pi brief VERBATIM under a rule. There is one brief
//     per role, and it lives in agents/<role>.md; a second copy would drift.
//
// The drift test (render-agents.test.ts) pins the rendered `tools:` to
// ROLE_TOOLS the same way agent-config-drift.test.ts pins pi's, so the two
// hosts' allowlists cannot come apart.

import { readFileSync, realpathSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { HOST_ENV } from "../../src/host.ts";
import { ARTIFACT_GATE_TOOLS, ROLE_TOOLS, type Role } from "../../src/path-policy.ts";
import { carriers, cliGates, gateCommand } from "./bash-policy.ts";

/** The pi tools with a bash carrier of their own (bash-policy.ts), beside
 *  the gates. */
const BASH_CARRIER_TOOLS = ["remove", "git", "sleep"] as const;

/**
 * The ONE mapping from pi's tool vocabulary to Claude Code's. A pi tool with a
 * Claude Code tool of its own maps to it; everything the pi extension
 * registers as a named tool — every artifact gate, git, sleep, remove — is
 * reached through Bash here and narrowed by the bash policy. The Bash rows
 * are derived from ARTIFACT_GATE_TOOLS, so a new gate maps without a hand
 * edit here.
 */
export const PI_TO_CLAUDE_TOOLS: Readonly<Record<string, string>> = {
  read: "Read",
  grep: "Grep",
  find: "Glob",
  ls: "Glob",
  write: "Write",
  edit: "Edit",
  subagent: "Agent",
  ...Object.fromEntries([...BASH_CARRIER_TOOLS, ...ARTIFACT_GATE_TOOLS].map((tool) => [tool, "Bash"])),
};

/** The harness root this host lives under: <root>/hosts/claude-code/. Derived
 *  through realpath so it survives the ~/.pi/agent symlink. */
export function defaultHarnessRoot(): string {
  return dirname(dirname(dirname(realpathSync(fileURLToPath(import.meta.url)))));
}

/** Marker line every rendered file carries, inside the frontmatter as a YAML
 *  comment so the model never sees it. The installer overwrites only files
 *  that have it. */
export const GENERATED_MARKER = "# generated by bounded-harness";

export function isGenerated(source: string): boolean {
  return source.split(/\r?\n/).some((line) => line.trim().startsWith(GENERATED_MARKER));
}

/** ROLE_TOOLS[role] in Claude Code's vocabulary: deduplicated, in first-
 *  appearance order. Throws on a pi tool the mapping does not know, so a new
 *  ROLE_TOOLS entry cannot silently render as nothing. */
export function claudeTools(role: Role): readonly string[] {
  const out: string[] = [];
  for (const tool of ROLE_TOOLS[role]) {
    const mapped = PI_TO_CLAUDE_TOOLS[tool];
    if (mapped === undefined) throw new Error(`no Claude Code tool for pi tool '${tool}' (${role})`);
    if (!out.includes(mapped)) out.push(mapped);
  }
  return out;
}

export interface RenderOptions {
  /** The harness checkout; agents/<role>.md is read from it and the hook path
   *  is built under it. */
  readonly harnessRoot: string;
  /** Override the hook command (tests, or a wrapper). Default: this host's
   *  hook under `harnessRoot`, bound with `--role <role>`. */
  readonly hookCommand?: string;
}

/** The hook command for a role, or the ambient (unbound) one when omitted. */
export function hookCommandFor(harnessRoot: string, role?: Role): string {
  const script = join(harnessRoot, "hosts", "claude-code", "path-gate-hook.ts");
  return `node "${script}"${role === undefined ? "" : ` --role ${role}`}`;
}

/** The parts of a pi agent definition this host reuses. */
export interface PiAgent {
  readonly description: string;
  /** Everything after the frontmatter, outer blank lines trimmed. */
  readonly body: string;
}

/** Read agents/<name>.md from the harness. Frontmatter is the block between
 *  the first two `---` lines; the description is its `description:` line. */
export function readPiAgent(harnessRoot: string, role: string): PiAgent {
  const source = readFileSync(join(harnessRoot, "agents", `${role}.md`), "utf8");
  const lines = source.split(/\r?\n/);
  const fences: number[] = [];
  for (let i = 0; i < lines.length && fences.length < 2; i++) {
    if (lines[i].trim() === "---") fences.push(i);
  }
  if (fences.length < 2) throw new Error(`agents/${role}.md: no frontmatter block`);
  const fm = lines.slice(fences[0] + 1, fences[1]);
  const descLine = fm.find((l) => l.startsWith("description:"));
  if (descLine === undefined) throw new Error(`agents/${role}.md: no description`);
  const body = lines.slice(fences[1] + 1).join("\n").replace(/^\n+/, "").replace(/\n+$/, "");
  return { description: descLine.slice("description:".length).trim(), body };
}

/** JSON string literals are valid YAML double-quoted scalars, and the pi
 *  descriptions contain `: ` and backticks that a plain scalar cannot hold. */
export const yamlString = (value: string): string => JSON.stringify(value);

/** The frontmatter lines that bind this host's PreToolUse hook to one
 *  definition: it fires for every tool call inside that subagent only. */
export function hookFrontmatter(command: string): readonly string[] {
  return [
    "hooks:",
    "  PreToolUse:",
    '    - matcher: ""',
    "      hooks:",
    "        - type: command",
    `          command: ${yamlString(command)}`,
  ];
}

const FILE_TOOLS_READ = ["read", "grep", "find", "ls"] as const;
const FILE_TOOLS_WRITE = ["write", "edit"] as const;

/**
 * The host preamble: how this role reaches each pi tool its brief names.
 * Generated from ROLE_TOOLS so it lists exactly what the role holds; the
 * brief below it is pi's and mentions tools by their pi names.
 */
export function renderPreamble(role: Role): string {
  const tools = ROLE_TOOLS[role];
  const has = (t: string): boolean => tools.includes(t);
  const lines: string[] = [];

  const reads = FILE_TOOLS_READ.filter(has);
  if (reads.length > 0) {
    const claude = [...new Set(reads.map((t) => PI_TO_CLAUDE_TOOLS[t]))];
    lines.push(`- ${reads.map(code).join(", ")} → the ${claude.join(", ")} tool${claude.length > 1 ? "s" : ""}.`);
  }
  const writes = FILE_TOOLS_WRITE.filter(has);
  if (writes.length > 0) {
    const claude = [...new Set(writes.map((t) => PI_TO_CLAUDE_TOOLS[t]))];
    lines.push(`- ${writes.map(code).join(", ")} → the ${claude.join(", ")} tool${claude.length > 1 ? "s" : ""}.`);
  }
  if (has("remove")) lines.push("- `remove` → `rm <path>` through Bash: one literal path, no flags, no patterns.");
  if (has("subagent")) {
    lines.push(
      "- `subagent` → the Agent tool, with `subagent_type` set to the role (`reviewer`, `test-writer`, `builder`) and the commission in `prompt`. One role per call; the phase gate refuses a commission whose preconditions are unmet. The project disables background tasks, so this call waits for its result; do not launch background sleeps or poll task files.",
    );
  }
  if (has("git")) lines.push("- `git` → read-only `git …` through Bash, one plain command per call; mutating Git commands are refused.");
  if (has("sleep")) lines.push("- `sleep` → `sleep <seconds>` through Bash, 1-120, only for a genuine delay unrelated to an Agent call.");
  for (const gate of cliGates(role)) {
    lines.push(`- \`${gate}\` → \`bounded gates ${gateCommand(gate)}\``);
  }

  return [
    "## This host: Claude Code",
    "",
    `You are the developer-stage **${role}**, running in Claude Code rather than pi. The brief below the rule is pi's, verbatim; this section is the only translation, and it says how each tool the brief names is reached here:`,
    "",
    ...lines,
    "",
    `Every gate is a command — \`bounded gates <gate> [dir] [--json]\`, run through Bash as one plain command: no \`&&\`, \`;\`, pipes, redirects or \`$(…)\`. Do not add an env prefix or pass \`--role\`: the hook prefixes \`${HOST_ENV}=claude-code BOUNDED_DEV_STAGE_ROLE=<role>\` itself, so the gate runs as the role this definition bound and records this host. \`bounded gates --list\` names them all.`,
    "",
    `Bash is refused for anything else — no package-manager commands, no \`cat\`, \`ls\`, \`find\` — and a refusal says why in one line. For this role Bash carries only: ${carriers(role)}. The path gate is a PreToolUse hook bound to this role, and every refusal is recorded in \`.bounded/guard-log.jsonl\`.`,
  ].join("\n");
}

const code = (s: string): string => `\`${s}\``;

/** One rendered `.claude/agents/<role>.md`. */
export function renderAgent(role: Role, opts: RenderOptions): string {
  const pi = readPiAgent(opts.harnessRoot, role);
  const command = opts.hookCommand ?? hookCommandFor(opts.harnessRoot, role);
  const frontmatter = [
    "---",
    `${GENERATED_MARKER} from agents/${role}.md — do not edit; re-run hosts/claude-code/install.ts`,
    `name: ${role}`,
    `description: ${yamlString(pi.description)}`,
    `tools: ${claudeTools(role).join(", ")}`,
    ...hookFrontmatter(command),
    "---",
  ];
  return [...frontmatter, "", renderPreamble(role), "", "---", "", pi.body, ""].join("\n");
}

export function renderAllAgents(opts: RenderOptions): Readonly<Record<Role, string>> {
  return {
    architect: renderAgent("architect", opts),
    "test-writer": renderAgent("test-writer", opts),
    builder: renderAgent("builder", opts),
    reviewer: renderAgent("reviewer", opts),
  };
}
