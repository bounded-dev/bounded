describe("bounded sync-config reinstalls through the composed setup commands", () => {
  test("a sync that changed config runs `bun install --frozen-lockfile --ignore-scripts`; an unchanged, installed one runs nothing", () => {
    const project = tsOnly();
    const ran: string[] = [];
    const run = (command: string, args: readonly string[], cwd: string): void => {
      ran.push([command, ...args].join(" "));
      mkdirSync(join(cwd, "node_modules", ".bun"), { recursive: true });
    };
    writeFileSync(join(project, "tsconfig.json"), "{}\n");
    const first = syncConfigCommand(project, agentRoot, run, fake);
    expect(first.code, first.lines.join("\n")).toBe(0);
    expect(ran).toEqual(["bun install --frozen-lockfile --ignore-scripts --linker isolated"]);
    expect(first.lines).toContain("sync-config: ran bun install --frozen-lockfile --ignore-scripts --linker isolated");
    expect(syncConfigCommand(project, agentRoot, run, fake).code).toBe(0);
    expect(ran).toHaveLength(1);
    rmSync(join(project, "node_modules"), { recursive: true, force: true });
    const broken = syncConfigCommand(project, agentRoot, () => { throw new Error("offline"); }, fake);
    expect(broken.code).toBe(1);
    expect(broken.lines.at(-1)).toMatch(/reinstall failed: bun install --frozen-lockfile --ignore-scripts/);
    const silent = syncConfigCommand(project, agentRoot, () => {}, fake);
    expect(silent.lines.at(-1)).toBe("sync-config: BLOCK — reinstall returned without node_modules/.bun");
  });
});

describe("every tool that spawns the test runner or type-checker refuses drifted config first", () => {
  const noSpawn = (): never => { throw new Error("spawned over drifted config"); };
  const project = tsOnly();
  writeFileSync(join(project, "bunfig.toml"), "[test]\npreload = ['./evil.ts']\n");

  test("run-tests: the primitive and the gate", async () => {
    const raw = await runTests(project, { run: noSpawn });
    expect(raw.blocked).toMatch(/config-drift: .*bunfig\.toml/);
    const gate = await runTestsGate(project, { run: noSpawn });
    expect(gate.lines).toContain("run_tests: route → orchestrator");
  });

  test("typecheck: the primitive and the gate", async () => {
    expect((await typecheck(project, { run: noSpawn })).diagnostics.join("\n")).toMatch(/config-drift: .*bunfig\.toml/);
    expect((await typecheckGate(project, "builder", { run: noSpawn })).lines).toContain("typecheck: route → orchestrator");
  });

  test("mutation-score and the phase gates refuse before running anything", async () => {
    const mutation = await runMutationScore(project, { runSuite: noSpawn });
    expect(mutation.lines, mutation.lines.join("\n")).toContain("mutation-score: route → orchestrator");
    for (const [gate, result] of [
      ["design-gate", await runDesignGate(project)],
      ["red-gate", await runRedGate(project)],
      ["green-gate", await runGreenGate(project)],
    ] as const) {
      expect(result.code, gate).toBe(1);
      expect(result.lines, gate).toContain(`${gate}: route → orchestrator`);
      expect(result.detail["step"], gate).toBe("config-drift");
    }
    expect(readGuardLog(project).filter((e) => (e.detail as { step?: unknown } | undefined)?.step === "config-drift").length).toBeGreaterThanOrEqual(5);
  });

  test("sync removes it, and the project is clean again", () => {
    expect(syncProjectConfig(project, agentRoot, fake).lines).toContain("sync-config: removed bunfig.toml (no composed pack generates it)");
    expect(configDriftReason(project, agentRoot)).toBeUndefined();
  });
});

describe("deliver on a generated project (ADR 2026-054, ADR 2026-062)", () => {
  test("finds the Bun wiring already generated, rewrites no config, and runs the check with bun", () => {
    const project = tsOnly();
    mkdirSync(join(project, "node_modules", "ts-morph"), { recursive: true });
    writeFileSync(join(project, "node_modules", "ts-morph", "package.json"), '{"name":"ts-morph"}\n');
    const before = readFileSync(join(project, "package.json"), "utf8");
    const calls: string[] = [];
    const result = runDeliver(project, {
      run: (command, args) => {
        calls.push([command, ...args].join(" "));
        return { code: 0, stdout: "", stderr: "" };
      },
    });
    expect(result.lines.join("\n")).not.toMatch(/\bnpm\b|experimental-strip-types/);
    expect(calls.every((c) => c.startsWith("bun "))).toBe(true);
    expect(calls.some((c) => c.startsWith("bun add"))).toBe(false);
    expect(readFileSync(join(project, "package.json"), "utf8")).toBe(before);
    expect(JSON.parse(before).scripts["check:surface"]).toBe(SURFACE_SCRIPT);
    expect(configDrift(project, agentRoot)).toEqual([]);
  });
});

