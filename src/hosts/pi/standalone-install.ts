import { randomUUID } from "node:crypto";
import { lstatSync } from "node:fs";
import { chmod, mkdir, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import type { HostInstallReport } from "bounded/application";
import type { Result } from "bounded/domain";
import { piLoader } from "./install.ts";

const LOADER = ".pi/extensions/bounded/index.ts";
const message = (error: unknown): string => error instanceof Error ? error.message : String(error);
const missing = (error: unknown): boolean => error instanceof Error && "code" in error && error.code === "ENOENT";

/** The project-local Pi file contains only the host bridge, never Bounded's rules or packages. */
export function standalonePiLoader(executable: string): string {
  return String.raw`// Generated by bounded. Pi loads this project's standalone Bounded bridge.
// The child command is bounded hook pi --project <root>.
import { spawn } from "node:child_process";
import { dirname, isAbsolute, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const executable = __BOUNDED_EXECUTABLE__;
const protocol = 1;
const maxFrameBytes = 1024 * 1024;
const maxQueuedFrames = 64;
const maxQueuedBytes = 1024 * 1024;
const deadlineMs = 20000;
const generationKey = Symbol.for("bounded.pi.standalone.generations");
const generations = globalThis[generationKey] ??= new Map();

export default function (pi) {
  generations.get(root)?.stop("Pi extension reloaded");
  let child;
  let started = false;
  let stopped = false;
  let broken;
  let nextId = 0;
  let pending;
  let responseBuffer = "";
  let queued = 0;
  let queuedBytes = 0;
  let tail = Promise.resolve();
  let sessionEpoch = 0;
  const reason = (cause) => "bounded's Pi worker cannot guard this call: " + cause + ". Repair the installed Bounded release and start a new Pi session";
  const block = (cause) => ({ block: true, reason: reason(cause) });
  const postError = (cause, event) => ({ content: [...(Array.isArray(event?.content) ? event.content : []),
    { type: "text", text: reason(cause) + "; after-tool checks could not complete" }], isError: true });
  const freeze = (value, seen = new Set()) => {
    if (typeof value !== "object" || value === null || seen.has(value)) return;
    seen.add(value);
    Object.freeze(value);
    for (const child of Object.values(value)) freeze(child, seen);
  };
  const contextFields = (context) => {
    const cwd = context?.cwd;
    if (typeof cwd !== "string" || !isAbsolute(cwd)) throw new Error("Pi context has no absolute cwd");
    return { cwd };
  };
  const validResult = (event, value) => {
    if (event === "session_start" || event === "subagent:async-complete") return value === null;
    if (value === null) return true;
    if (typeof value !== "object" || value === null || Array.isArray(value)) return false;
    if (event === "tool_call") return Object.keys(value).sort().join() === "block,reason"
      && value.block === true && typeof value.reason === "string" && value.reason !== "";
    if (event === "tool_result") return Object.keys(value).sort().join() === "content,isError"
      && Array.isArray(value.content) && value.isError === true;
    return false;
  };
  const stop = (cause) => {
    if (broken === undefined) broken = cause;
    stopped = true;
    if (pending !== undefined) { clearTimeout(pending.timer); pending.reject(new Error(broken)); pending = undefined; }
    child?.stdin?.destroy();
    child?.kill();
  };
  const replaceSessionWorker = () => {
    const previousChild = child;
    sessionEpoch++;
    if (pending !== undefined) {
      clearTimeout(pending.timer);
      pending.reject(new Error("Pi session replaced"));
      pending = undefined;
    }
    child = undefined;
    responseBuffer = "";
    queued = 0;
    queuedBytes = 0;
    tail = Promise.resolve();
    previousChild?.stdin?.destroy();
    previousChild?.kill();
  };
  generations.set(root, { stop });
  const receive = (activeChild, chunk) => {
    if (activeChild !== child) return;
    responseBuffer += chunk.toString("utf8");
    if (Buffer.byteLength(responseBuffer) > maxFrameBytes) { stop("oversized worker response"); return; }
    for (;;) {
      const end = responseBuffer.indexOf("\n");
      if (end < 0) return;
      const line = responseBuffer.slice(0, end);
      responseBuffer = responseBuffer.slice(end + 1);
      let answer;
      try { answer = JSON.parse(line); } catch { stop("malformed worker response"); return; }
      if (pending === undefined || answer?.protocol !== protocol || answer.id !== pending.id || answer.event !== pending.event
        || !Object.hasOwn(answer, "result") || Object.keys(answer).sort().join() !== "event,id,protocol,result") {
        stop("out-of-order or malformed worker response"); return;
      }
      if (!validResult(pending.event, answer.result)) { stop("worker response has invalid result"); return; }
      const waiting = pending;
      pending = undefined;
      clearTimeout(waiting.timer);
      waiting.resolve(answer.result);
    }
  };
  const begin = () => {
    if (child !== undefined || broken !== undefined) return;
    try {
      const activeChild = spawn(executable, ["hook", "pi", "--project", root], { stdio: ["pipe", "pipe", "pipe"], windowsHide: true });
      child = activeChild;
      activeChild.stdout.on("data", (chunk) => receive(activeChild, chunk));
      activeChild.stderr.on("data", () => {}); // Drain diagnostics even when the child writes continuously.
      activeChild.on("error", (error) => { if (activeChild === child) stop(error.message); });
      activeChild.on("exit", () => { if (activeChild === child) stop("worker exited"); });
    } catch (error) { stop(error instanceof Error ? error.message : String(error)); }
  };
  const request = (epoch, event, payload, context) => new Promise((resolveRequest, rejectRequest) => {
    if (epoch !== sessionEpoch) { rejectRequest(new Error("Pi session replaced")); return; }
    if (broken !== undefined || stopped) { rejectRequest(new Error(broken ?? "worker stopped")); return; }
    begin();
    if (child === undefined || broken !== undefined) { rejectRequest(new Error(broken ?? "worker did not start")); return; }
    const id = ++nextId;
    let line;
    try { line = JSON.stringify({ protocol, id, event, payload, context }) + "\n"; }
    catch { rejectRequest(new Error("Pi event cannot be serialized")); return; }
    if (Buffer.byteLength(line) > maxFrameBytes) { stop("oversized Pi event"); rejectRequest(new Error("oversized Pi event")); return; }
    const timer = setTimeout(() => stop("worker response timed out"), deadlineMs);
    pending = { id, event, timer, resolve: resolveRequest, reject: rejectRequest };
    const activeChild = child;
    activeChild.stdin.write(line, (error) => { if (error && activeChild === child) stop(error.message); });
  });
  const enqueue = (event, payload, context) => {
    // Increment before any await so Pi's unawaited event bus still orders the next tool call.
    let frameBytes;
    try { frameBytes = Buffer.byteLength(JSON.stringify({ protocol, id: Number.MAX_SAFE_INTEGER, event, payload, context }) + "\n"); }
    catch { return Promise.reject(new Error("Pi event cannot be serialized")); }
    if (frameBytes > maxFrameBytes || ++queued > maxQueuedFrames || queuedBytes + frameBytes > maxQueuedBytes) {
      stop("Pi event queue overflow or oversized frame");
      return Promise.reject(new Error("Pi event queue overflow or oversized frame"));
    }
    queuedBytes += frameBytes;
    const epoch = sessionEpoch;
    const work = tail.then(() => request(epoch, event, payload, context));
    tail = work.then(() => undefined, () => undefined);
    void work.finally(() => { if (epoch === sessionEpoch) { queued--; queuedBytes -= frameBytes; } }).catch(() => {});
    return work;
  };
  pi.on("tool_call", async (event, context) => {
    if (broken !== undefined) return block(broken);
    if (!started) return block("tool call arrived before session start");
    try { freeze(event?.input); return await enqueue("tool_call", event, contextFields(context)); }
    catch (error) { return block(error instanceof Error ? error.message : String(error)); }
  });
  pi.on("session_start", async (event, context) => {
    if (stopped) return;
    if (started) replaceSessionWorker();
    started = true;
    try { await enqueue("session_start", event, contextFields(context)); } catch (error) { stop(error instanceof Error ? error.message : String(error)); }
  });
  pi.on("tool_result", async (event, context) => {
    if (broken !== undefined) return postError(broken, event);
    if (!started) return postError("result arrived before session start", event);
    try { return await enqueue("tool_result", event, contextFields(context)); }
    catch (error) { return postError(error instanceof Error ? error.message : String(error), event); }
  });
  if (typeof pi.events?.on !== "function") stop("Pi async completion event bus is unavailable");
  else try {
    pi.events.on("subagent:async-complete", (payload) => {
      const acknowledged = enqueue("subagent:async-complete", payload, { cwd: root });
      return acknowledged.then(() => undefined, () => undefined);
    });
  } catch { stop("Pi event bus registration failed"); }
}
`.replace("__BOUNDED_EXECUTABLE__", JSON.stringify(executable));
}

export interface PreparedStandalonePiExtension {
  readonly loaderPath: string;
  readonly originalBytes: string | null;
  readonly nextBytes: string;
  readonly mode: number;
  install(): Promise<Result<HostInstallReport>>;
  restore(): Promise<void>;
}

async function replaceLoader(path: string, bytes: string, mode: number, recheck: () => Promise<Result<undefined>>): Promise<void> {
  const staged = join(dirname(path), `.bounded-pi-${randomUUID()}.tmp`);
  try {
    await writeFile(staged, bytes, { flag: "wx", mode });
    await chmod(staged, mode);
    const current = await recheck();
    if (!current.ok) throw new Error(current.error);
    await rename(staged, path);
  } finally { await rm(staged, { force: true }); }
}

function validDirectory(path: string, required: boolean): Result<undefined> {
  try {
    const info = lstatSync(path);
    return info.isDirectory() && !info.isSymbolicLink() ? { ok: true, value: undefined }
      : { ok: false, error: `${path} is linked or not a directory` };
  } catch (error) {
    if (missing(error)) return required ? { ok: false, error: `${path} is missing; create it before bounded init --host pi` }
      : { ok: true, value: undefined };
    return { ok: false, error: `${path} cannot be inspected: ${message(error)}` };
  }
}

/** Prepare Pi's generated bridge without changing any project file. */
export async function prepareStandalonePiExtension(projectRoot: string, executable: string): Promise<Result<PreparedStandalonePiExtension>> {
  for (const [relative, required] of [[".pi", true], [".pi/extensions", false], [".pi/extensions/bounded", false]] as const) {
    const checked = validDirectory(join(projectRoot, relative), required);
    if (!checked.ok) return checked;
  }
  const loaderPath = join(projectRoot, LOADER);
  let originalBytes: string | null = null;
  let mode = 0o644;
  try {
    const info = lstatSync(loaderPath);
    if (!info.isFile() || info.isSymbolicLink()) return { ok: false, error: `${LOADER} is linked or not a regular file` };
    originalBytes = await readFile(loaderPath, "utf8");
    mode = (await stat(loaderPath)).mode & 0o777;
    if (originalBytes !== piLoader().content && originalBytes !== standalonePiLoader(executable))
      return { ok: false, error: `${LOADER} contains user edits or an unknown loader; preserve it and migrate manually` };
  } catch (error) { if (!missing(error)) return { ok: false, error: `${LOADER} cannot be inspected: ${message(error)}` }; }
  const nextBytes = standalonePiLoader(executable);
  const recheck = async (expectedBytes: string | null): Promise<Result<undefined>> => {
    for (const [relative, required] of [[".pi", true], [".pi/extensions", false], [".pi/extensions/bounded", false]] as const) {
      const checked = validDirectory(join(projectRoot, relative), required);
      if (!checked.ok) return checked;
    }
    try {
      const info = lstatSync(loaderPath);
      if (!info.isFile() || info.isSymbolicLink()) return { ok: false, error: `${LOADER} changed to a link or unsupported entry after inspection; retry` };
      if (expectedBytes === null || await readFile(loaderPath, "utf8") !== expectedBytes || ((await stat(loaderPath)).mode & 0o777) !== mode)
        return { ok: false, error: `${LOADER} changed after inspection; preserve the user edit and retry` };
    } catch (error) {
      if (!missing(error)) return { ok: false, error: `${LOADER} cannot be rechecked: ${message(error)}` };
      if (expectedBytes !== null) return { ok: false, error: `${LOADER} disappeared after inspection; retry` };
    }
    return { ok: true, value: undefined };
  };
  return { ok: true, value: {
    loaderPath, originalBytes, nextBytes, mode,
    async install() {
      if (originalBytes === nextBytes) return { ok: true, value: { host: "pi", changedPaths: [], skippedBecause: null } };
      try {
        const current = await recheck(originalBytes);
        if (!current.ok) return current;
        await mkdir(dirname(loaderPath), { recursive: true });
        await replaceLoader(loaderPath, nextBytes, mode, () => recheck(originalBytes));
        return { ok: true, value: { host: "pi", changedPaths: [LOADER], skippedBecause: null } };
      } catch (error) { return { ok: false, error: `${LOADER} could not be replaced: ${message(error)}` }; }
    },
    async restore() {
      const current = await recheck(nextBytes);
      if (!current.ok) {
        const unchangedOriginal = await recheck(originalBytes);
        if (unchangedOriginal.ok) return;
        throw new Error(`${LOADER} changed after installation; preserve the user edit before rolling back`);
      }
      if (originalBytes === null) await rm(loaderPath, { force: true });
      else await replaceLoader(loaderPath, originalBytes, mode, () => recheck(nextBytes));
    },
  } };
}
